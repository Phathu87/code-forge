// Educational content, versioned separately from learner progress.
export const modules = [];
export function unit(
  title,
  why,
  example,
  explanation,
  code,
  practice,
  broken,
  debug,
  application,
) {
  return {
    title,
    objective: practice,
    why,
    example,
    explanation,
    code,
    practice,
    broken,
    debug,
    application,
  };
}
export function module(
  id,
  title,
  level,
  prerequisites,
  skills,
  lessons,
  mission,
  assessment,
) {
  modules.push({
    id,
    title,
    level,
    prerequisites: prerequisites.map((target) => ({
      target: target.replace(/^\?/, ""),
      type: "skill",
      strength: target.startsWith("?") ? "soft" : "hard",
    })),
    skills,
    lessons,
    mission,
    assessment,
  });
}
export function task(
  id,
  title,
  brief,
  requirements,
  explanation,
  modification,
  bonus = [],
) {
  return { id, title, brief, requirements, explanation, modification, bonus };
}
